export function dictionaryFor(locale: Locale): Dictionary {
  return dictionaries[locale] ?? dictionaries.en;
}

/** Localize Western digits into locale numerals (e.g., "7" → "৭"). */
export function localizeNumber(value: number | string, locale: Locale): string {
  const s = String(value);
  const digits = LOCALE_META[locale]?.digits ?? LOCALE_META.en.digits;
  if (digits.every((d) => d === LOCALE_META.en.digits[Number(d)])) return s;
  return s.replace(/\d/g, (d) => digits[Number(d)]);
}
